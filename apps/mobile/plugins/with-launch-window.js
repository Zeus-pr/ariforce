/**
 * Seamless Android launch (config plugin; applies on prebuild / `expo run:android`).
 *
 * Problem (measured on the API 37 emulator, 2026-10-29): expo-splash-screen blocks the activity
 * window from drawing (OnPreDrawListener returns false) until JS calls hideAsync. On a debug build
 * JS needs seconds to load, the system logs "Activity transferring splash screen timeout", removes
 * its starting window, and the never-drawn activity window shows black/blank until React paints.
 * Then the JS splash pops in: the flicker between the two splashes.
 *
 * Fix: the activity window itself looks exactly like the system splash, and is allowed to draw
 * straight away.
 * 1. drawable/ariforce_launch_window: splash ground + the generated splashscreen_logo (288dp
 *    canvas, the same artwork, size and centre the system splash uses).
 * 2. MainActivity: window background = that drawable, and SplashScreenManager.hide() right away so
 *    the system splash hands over on the first frame (its fade runs over identical pixels).
 * 3. The JS BrandSplash is transparent until its own mark (same artwork, size, centre) is painted,
 *    so the window's mark shows through while it decodes. The window background is left in place:
 *    every screen is opaque (Stack contentStyle = ground), so it is never seen again.
 */
const { withDangerousMod, withMainActivity } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const TAG = 'ariforce-launch-window';
const DRAWABLE = 'ariforce_launch_window';

const DRAWABLE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- @generated by ${TAG} (apps/mobile/plugins/with-launch-window.js) -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
  <item android:drawable="@color/splashscreen_background" />
  <item
    android:width="288dp"
    android:height="288dp"
    android:gravity="center"
    android:drawable="@drawable/splashscreen_logo" />
</layer-list>
`;

const KOTLIN = `    // @generated begin ${TAG}
    // Draw the splash look in this window at once (see apps/mobile/plugins/with-launch-window.js).
    window.setBackgroundDrawableResource(R.drawable.${DRAWABLE})
    SplashScreenManager.hide()
    // @generated end ${TAG}
`;

function patchMainActivity(src) {
  let out = src.replace(
    new RegExp(`\\n?\\s*// @generated begin ${TAG}[\\s\\S]*?// @generated end ${TAG}\\n`),
    '\n',
  );
  const anchor = /^(\s*)super\.onCreate\([^)]*\)\s*$/m;
  if (!anchor.test(out)) throw new Error(`[${TAG}] super.onCreate(...) not found in MainActivity`);
  out = out.replace(anchor, (line) => `${line}\n${KOTLIN.trimEnd()}`);
  return out;
}

module.exports = function withLaunchWindow(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/drawable');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${DRAWABLE}.xml`), DRAWABLE_XML);
      return cfg;
    },
  ]);
  return withMainActivity(config, (cfg) => {
    if (cfg.modResults.language !== 'kt')
      throw new Error(`[${TAG}] expected a Kotlin MainActivity`);
    cfg.modResults.contents = patchMainActivity(cfg.modResults.contents);
    return cfg;
  });
};

module.exports.patchMainActivity = patchMainActivity;
