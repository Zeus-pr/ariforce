"""Builds src/mocks/product-seed.ts from Arighna's product sheet (read-only, stdlib only).
Usage: python3 scripts/gen-product-seed.py /Volumes/Prajesh_ext_512/AriForce-data/arighna-all-products.xlsx"""
import json, re, sys, zipfile, xml.etree.ElementTree as ET

M = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
z = zipfile.ZipFile(sys.argv[1])
ss = [''.join(t.text or '' for t in si.iter(M + 't')) for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(M + 'si')]
out = []
for r in ET.fromstring(z.read('xl/worksheets/sheet1.xml')).iter(M + 'row'):
    row = {}
    for c in r.findall(M + 'c'):
        v = c.find(M + 'v')
        if v is not None:
            row[re.match('[A-Z]+', c.get('r')).group()] = ss[int(v.text)] if c.get('t') == 's' else v.text
    if not row.get('B', '').isdigit():
        continue
    n = int(row['B'])
    out.append({
        'id': f'01930000-0000-7000-8a00-{n:012d}',
        'name': row['D'].strip(),
        'composition': row.get('F', '').strip(),
        'category': row.get('H', '').strip(),
        'packSize': row.get('J', '').strip(),
    })
body = json.dumps(out, indent=2, ensure_ascii=False)
open('src/mocks/product-seed.ts', 'w').write(f"""/**
 * MOCK SEED, not an API contract. Generated by scripts/gen-product-seed.py from Arighna's product sheet
 * (arighna-all-products.xlsx, {len(out)} products). Used for product pickers in mock mode only, because the
 * contract mock (packages/contracts) ships two placeholder products. The real master lives in Supabase.
 * MRP/PTR/PTS are not in the sheet. Ids are local placeholders.
 */
export type SeedProduct = {{ id: string; name: string; composition: string; category: string; packSize: string }};

export const MOCK_PRODUCT_SEED: SeedProduct[] = {body};
""")
print(len(out))
