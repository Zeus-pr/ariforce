/**
 * Generates docs/api/openapi.json and src/generated/openapi.ts from the zod contracts.
 * `--check` fails if either committed file is stale (used by CI).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';
import { buildOpenApiDocument } from '../src/openapi';

const root = resolve(import.meta.dirname, '../../..');
const jsonPath = resolve(root, 'docs/api/openapi.json');
const tsPath = resolve(import.meta.dirname, '../src/generated/openapi.ts');
const check = process.argv.includes('--check');

const doc = buildOpenApiDocument();
const jsonOut = JSON.stringify(doc, null, 2) + '\n';
const ast = await openapiTS(JSON.parse(jsonOut));
const prettierCfg = (await resolveConfig(tsPath)) ?? {};
const tsOut = await format(
  '// GENERATED by scripts/openapi.ts. Do not edit.\n' + astToString(ast),
  { ...prettierCfg, parser: 'typescript' },
);

let stale = false;
for (const [p, out] of [
  [jsonPath, jsonOut],
  [tsPath, tsOut],
] as const) {
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : '';
  if (cur === out) continue;
  if (check) {
    console.error(`STALE: ${p}. Run: pnpm -F @ariforce/contracts openapi`);
    stale = true;
  } else {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, out);
    console.log(`wrote ${p}`);
  }
}
if (stale) process.exit(1);
